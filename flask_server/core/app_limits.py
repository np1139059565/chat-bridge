"""
AI 工具调用镜像插件 —— 数量上限的唯一来源

为什么要集中：
    此前各模块各自定义上限，彼此不知情，出现了互不匹配的错位——
    例如「收件箱消息保留 500 条」而「音频只保留 100 个」，
    而每条带语音的消息引用一个音频，导致旧音频被删、消息仍在、
    前端请求音频得到 404（表现为「语音播放失败」）。

统一原则：
    1. 同一批资源、且存在引用关系的，用同一基准值派生，保证口径一致；
    2. 量纲不同、生命周期不同的（日志队列 / 文本长度 / 并发数），
       不强行同值，但集中于此，改一处即可全局可见。

改动约定：
    调整任何上限只改本文件，各模块从此处导入，不再就地定义。
"""

# ========== 一、网页会话保留（存在引用关系，必须同口径）==========
# 基准：网页会话保留条数。收件箱消息与其引用的音频共用此基准，
# 保证「消息还在时，它引用的音频一定还在」。
WEB_RETENTION = 500

# 收件箱消息上限（条）：超出丢弃最旧。
MAX_MESSAGES = WEB_RETENTION

# 音频文件上限（个）：与消息同基准。每条带语音的消息至多引用一个音频，
# 故音频保留数与消息保留数相等即可覆盖；另有「引用保护」兜底（见 web_mirror），
# 仍被消息引用的音频即使很旧也不会被删。
MAX_AUDIO_FILES = WEB_RETENTION

# ========== 二、卡片总线 ==========
# 卡片是「待投递」的临时队列，被取走并确认后即不再需要，与消息保留量无关。
# 内存敏感：图片卡片含完整 base64，单张可达 1MB+，故不随 WEB_RETENTION 放大。
MAX_CARDS = 200

# ========== 三、推送与日志 ==========
# 单次抽屉上报最多推送的消息条数（防一次推太多刷屏）。
MAX_PUSH_PER_REPORT = 30

# 异步日志队列容量（条）：消费跟不上时丢最旧，兜住内存。
LOG_QUEUE_MAX = 10000

# ========== 四、文本与结果长度（字符）==========
# 工具结果 JSON 体积上限（可被 runtime.yaml 覆盖）。
DEFAULT_MAX_JSON_CHARS = 100000
# 技能文档读取上限。
MAX_DOC_CHARS = 200000

# ========== 五、并发与重试 ==========
# 语音合成同时在线数上限（防打爆在线服务、防线程无上限增长）。
MAX_CONCURRENT_SYNTH = 3
# 语音合成失败重试次数与间隔（秒）：edge-tts 偶发失败，重试多为暂时性。
SYNTH_RETRY = 3
SYNTH_RETRY_INTERVAL = 1.0
